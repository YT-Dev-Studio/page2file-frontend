import { mkdir, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const contentRoot = join(projectRoot, "content");
const outputPath = join(
  projectRoot,
  "src",
  "content",
  "generated",
  "localized-blog-components.ts",
);
const locales = [
  "de",
  "fr",
  "es",
  "nl",
  "pt",
  "it",
  "pl",
  "cs",
  "sv",
  "no",
  "da",
  "fi",
  "ro",
  "hu",
];

const toIdentifier = (locale, slug) =>
  `${locale}_${slug}`
    .replaceAll(/[^a-zA-Z0-9]+/g, "_")
    .replace(/^(\d)/, "_$1");

const imports = [];
const localeEntries = [];

for (const locale of locales) {
  const directory = join(contentRoot, locale, "blog");
  let filenames = [];
  try {
    filenames = (await readdir(directory))
      .filter((filename) => filename.endsWith(".mdx"))
      .sort();
  } catch (error) {
    if (error?.code !== "ENOENT") {
      throw error;
    }
  }

  if (filenames.length === 0) {
    continue;
  }

  const entries = filenames.map((filename) => {
    const slug = filename.slice(0, -4);
    const identifier = toIdentifier(locale, slug);
    const sourcePath = relative(dirname(outputPath), join(directory, filename))
      .split(sep)
      .join("/");
    imports.push(`import ${identifier} from "${sourcePath}";`);
    return `    "${slug}": ${identifier},`;
  });

  localeEntries.push(`  ${locale}: {\n${entries.join("\n")}\n  },`);
}

const source = `/* This file is generated by scripts/generate-localized-content.mjs. */
import type { ComponentType } from "react";
import type { Locale } from "@/shared/i18n/locales";
${imports.join("\n")}

export const localizedBlogComponents: Partial<
  Record<Locale, Record<string, ComponentType>>
> = {
${localeEntries.join("\n")}
};
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, "utf8");
console.log(
  `Localized MDX import map generated: ${imports.length} article component(s).`,
);
